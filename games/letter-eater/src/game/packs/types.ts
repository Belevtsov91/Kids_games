// Набор букв и слов для одного языка: алфавит, похожие буквы, названия букв вслух и слова уровней.

export interface Word {
  word: string;
  emoji: string;
  /** Ключ готовой картинки из ui/art.ts, если слово на этом языке другое, а картинка та же. */
  art?: string;
}

export interface LanguagePack {
  /** Только заглавные буквы. */
  alphabet: string;
  /** Буквы, которые дети часто путают: лишние буквы на сложных уровнях берутся отсюда. */
  similar: Record<string, string>;
  /** Как буква называется вслух: голос браузера читает одиночные буквы по-разному, поэтому подсказываем. */
  letterNames: Record<string, string>;
  /** Названия и слова пяти уровней, по порядку. */
  levels: { title: string; words: Word[] }[];
}
